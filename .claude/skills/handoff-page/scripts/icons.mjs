// The icons a page draws: the manual's page icons (tools/manual/src/content/icons.ts) and the few more the digest names for
// platform pages and ways of working, copied as duotone paths from the Phosphor package the manual draws with, into
// template.html between its icons markers, so the page stays one file with nothing to fetch.
// node icons.mjs           - rewrites the block from the Phosphor package
// node icons.mjs --check   - fails when the block is not what the list draws
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "../../../..");
const TEMPLATE = join(HERE, "../assets/template.html");
const MANUAL = readFileSync(
  join(ROOT, "tools/manual/src/content/icons.ts"),
  "utf8",
);
const manualIcons = [
  ...MANUAL.slice(MANUAL.indexOf("PAGE_ICONS")).matchAll(/^\s+"([a-z-]+)",$/gm),
].map((m) => m[1]);
export const EXTRA = [
  "app-window",
  "arrows-left-right",
  "book-open",
  "chart-line-up",
  "check-square",
  "clock",
  "coins",
  "database",
  "globe",
  "hard-drives",
  "layout",
  "lightning",
  "lock-key",
  "newspaper",
  "path",
  "stack",
  "translate",
  "user-list",
  "wrench",
];
const NAMES = [...new Set([...manualIcons, ...EXTRA])].sort();
const START =
  "    // icons:start - generated by scripts/icons.mjs from @phosphor-icons/react duotone; do not edit by hand";
const END = "    // icons:end";

function draw(name) {
  const pkg = realpathSync(
    join(ROOT, "tools/manual/node_modules/@phosphor-icons/react"),
  );
  const file = name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
  const src = readFileSync(join(pkg, "dist/defs", `${file}.es.js`), "utf8");
  const duo = src.slice(src.indexOf('"duotone"'), src.indexOf('"fill"'));
  const paths = [...duo.matchAll(/d: "([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 2)
    throw new Error(
      `${name}: expected a duotone back and front path, found ${paths.length}`,
    );
  return paths;
}

export function block() {
  const lines = NAMES.map(
    (n) => `      ${JSON.stringify(n)}: ${JSON.stringify(draw(n))},`,
  );
  return [START, "    const ICONS = {", ...lines, "    };", END].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const html = readFileSync(TEMPLATE, "utf8");
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a < 0 || b < 0) throw new Error("template.html has no icons markers");
  const next = html.slice(0, a) + block() + html.slice(b + END.length);
  if (process.argv.includes("--check")) {
    if (next !== html) {
      console.error(
        "FAIL template.html's icons are not what scripts/icons.mjs draws: run node scripts/icons.mjs",
      );
      process.exit(1);
    }
    console.log(`icons: ${NAMES.length} in step`);
  } else {
    writeFileSync(TEMPLATE, next);
    console.log(`icons: wrote ${NAMES.length}`);
  }
}
