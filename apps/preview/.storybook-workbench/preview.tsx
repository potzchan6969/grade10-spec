import type { Preview } from "@storybook/react-vite";
import basePreview from "../.storybook/preview";
import { withGiven } from "./given";
import { withJourneys } from "./journeys";
import { ManualDocsContainer } from "./manual-link";

/* Themes, frames, and decorators come from the base preview. The sidebar reads
 * like the manual (`docs/governance/storybook.md`): Start Here, the manual's
 * domains in `docs/prds/manual.yaml` order with their features in the manual's
 * nav order after the domain's Flows, then the design system; inside a
 * feature, Screens, Prototypes, Parts and Blocks.
 *
 * Storybook evaluates this comparator on its own, so it imports nothing and
 * carries no types; `pnpm storybook:sort` writes `sidebar` from the manual and
 * `pnpm storybook:check` refuses a stale one. A story's journeys show under its
 * canvas (`journeys.tsx`); a Scenario's settings and journeys show in the Given
 * panel (`given.tsx`, `manager.tsx`). */
const preview: Preview = {
  ...basePreview,
  decorators: [...(basePreview.decorators ?? []), withJourneys, withGiven],
  parameters: {
    ...basePreview.parameters,
    docs: { ...basePreview.parameters?.docs, container: ManualDocsContainer },
    options: {
      ...basePreview.parameters?.options,
      storySort: (a, b) => {
        // biome-ignore format: generated by `pnpm storybook:sort`
        const sidebar = {
          "Start Here": [],
          "Account": ["Profile", "Sign In", "KYC", "Business Verification", "Kyc Service", "Roles", "Users", "Sessions", "Audit", "Earnings Wallet", "Accounts"],
          "Store": ["Home", "Product Listing", "Product Page", "Cart", "Cart Validation", "Store Locator", "Cross Sell", "Checkout", "Order History", "Order Detail", "Shelf Scanning", "Discounts", "Refunds", "Shipping"],
          "Loyalty": ["Points", "Tiers", "Rewards", "Paying With Points", "Coupons", "Membership", "Shopify Integration", "Campaigns", "Wallet Member Card", "Operator Console", "Expiry Reminders", "Top Ups"],
          "Auction": ["Account", "Display", "Bidding", "Post Bidding"],
          "Vault": ["Deposit", "Incentive", "Portfolio", "Vault Withdrawal", "Documents", "Operations"],
          "Submissions": ["Intake Tracker"],
          "Grading": ["Planning", "Drop Off", "Submission", "Documents", "Messages"],
          "Consignment": ["Consigning", "Ending A Consignment", "Dashboard", "Operator Console"],
          "Appointment": ["Booking", "Visit"],
          "Ticketing": ["Buying", "Waiting Line", "Your Tickets"],
          "Doc Sign": ["Service"],
          "Finance": ["Collector Pages", "Case Lifecycle", "Loan And Money", "Documents And Signing", "Identity Check", "Operator Console", "Compliance And Readiness"],
          "Site": ["Page Shell", "Crawlable Pages", "Navigation", "Carried Surfaces", "Typography", "About", "Shows", "Press", "Media Coverage"],
          "Analytics": ["Mixpanel Events", "Datadog Counters", "Site Records"],
          "Commerce": ["Commerce", "Checkout Domain", "Site Content", "Order Status", "Product Status"],
          "Design System": [],
        };
        const roots = Object.keys(sidebar);
        const kinds = ["Screens", "Prototypes", "Parts", "Blocks"];
        const left = a.title.split("/");
        const right = b.title.split("/");
        const rank = (list, item) =>
          list.includes(item) ? list.indexOf(item) : list.length;
        if (left[0] !== right[0]) {
          const order = rank(roots, left[0]) - rank(roots, right[0]);
          return order || left[0].localeCompare(right[0]);
        }
        for (let i = 1; i < Math.max(left.length, right.length); i++) {
          if (left[i] === right[i]) continue;
          if (left[i] === undefined) return -1;
          if (right[i] === undefined) return 1;
          if (i === 1) {
            if (left[i] === "Flows") return -1;
            if (right[i] === "Flows") return 1;
            const features = sidebar[left[0]] ?? [];
            const order = rank(features, left[i]) - rank(features, right[i]);
            if (order) return order;
          }
          if (i === 2 && left[0] !== "Design System") {
            const order =
              kinds.indexOf(left[i]) + 1 - (kinds.indexOf(right[i]) + 1);
            if (order) return order;
          }
          return left[i].localeCompare(right[i], undefined, { numeric: true });
        }
        return 0;
      },
    },
  },
};

export default preview;
