/**
 * The manual tree the workbench sidebar draws. Storybook evaluates `storySort`
 * on its own, so `pnpm storybook:sort` writes the tree into it as a literal and
 * `pnpm storybook:check` refuses one that is not the manual's.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { DESIGN_SYSTEM, START_HERE, titleCase } from "./grammar.mjs";
import { rootDirectory } from "./story-index.mjs";

export const WORKBENCH_PREVIEW =
  "apps/preview/.storybook-workbench/preview.tsx";
const SITE = "docs/prds/products/grade10-site";
const IGNORE = "// biome-ignore format: generated by `pnpm storybook:sort`";
const STATEMENT = new RegExp(
  `^( *)${IGNORE}\\n\\1const sidebar = \\{\\n[\\s\\S]*?^\\1\\};$`,
  "m",
);

function frontmatter(path) {
  const match = /^---\n([\s\S]*?)\n---/.exec(readFileSync(path, "utf8"));
  return (match && parse(match[1])) ?? {};
}

/** Every feature the workbench sidebar can hold, with its page's `order` and `title`. */
export function manualFeatures(root = rootDirectory) {
  const features = [];
  for (const domain of readdirSync(join(root, SITE)).sort()) {
    if (domain.includes(".")) continue;
    for (const file of readdirSync(join(root, SITE, domain)).sort()) {
      if (!file.endsWith(".md") || file === "index.md" || file === "README.md")
        continue;
      const feature = file.slice(0, -3);
      const page = `${SITE}/${domain}/${file}`;
      const { order, title } = frontmatter(join(root, page));
      features.push({
        key: `${domain}/${feature}`,
        domain,
        name: titleCase(feature),
        title: `${titleCase(domain)}/${titleCase(feature)}`,
        page,
        order: typeof order === "number" ? order : Number.MAX_SAFE_INTEGER,
        heading: title ?? titleCase(feature),
      });
    }
  }
  return features;
}

/** The grade10-site domains, as slugs, in `docs/prds/manual.yaml` order. */
function manualDomains(root) {
  const manual = parse(
    readFileSync(join(root, "docs/prds/manual.yaml"), "utf8"),
  );
  const products = Object.values(manual.groups ?? {}).flat();
  return [
    ...new Set(
      products
        .filter((product) => product.startsWith("grade10-site/"))
        .map((product) => product.split("/")[1]),
    ),
  ];
}

/**
 * `{ root: [feature, …] }` in the manual's nav order: Start Here, the domains,
 * each with its features by `order:` then page title, then the design system.
 */
export function sidebar(root = rootDirectory) {
  const features = manualFeatures(root).sort(
    (left, right) =>
      left.order - right.order || left.heading.localeCompare(right.heading),
  );
  const tree = { [START_HERE]: [] };
  for (const domain of manualDomains(root))
    tree[titleCase(domain)] = features
      .filter((feature) => feature.domain === domain)
      .map((feature) => feature.name);
  tree[DESIGN_SYSTEM] = [];
  return tree;
}

/** The `const sidebar` statement `storySort` carries, at `indent`. */
export function renderSidebar(tree, indent = "") {
  const rows = Object.entries(tree).map(
    ([name, features]) =>
      `${indent}  ${JSON.stringify(name)}: [${features.map((feature) => JSON.stringify(feature)).join(", ")}],`,
  );
  return [
    `${indent}${IGNORE}`,
    `${indent}const sidebar = {`,
    ...rows,
    `${indent}};`,
  ].join("\n");
}

/**
 * The preview's source with its sidebar statement rewritten from the manual,
 * or null when it holds none.
 */
export function sortedPreview(previewText, root = rootDirectory) {
  const match = STATEMENT.exec(previewText);
  if (!match) return null;
  return previewText.replace(match[0], () =>
    renderSidebar(sidebar(root), match[1]),
  );
}

export const MISSING = `${WORKBENCH_PREVIEW} - storySort holds no generated \`const sidebar\` statement`;

function main() {
  const path = join(rootDirectory, WORKBENCH_PREVIEW);
  const before = readFileSync(path, "utf8");
  const after = sortedPreview(before);
  if (after === null) throw new Error(MISSING);
  if (after === before)
    console.log(`${WORKBENCH_PREVIEW} already reads the manual.`);
  else {
    writeFileSync(path, after);
    console.log(`${WORKBENCH_PREVIEW} now reads the manual.`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
